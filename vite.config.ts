import { createRequire } from 'node:module'
import path from 'node:path'

import { defineConfig, lazyPlugins } from 'vite-plus'
import { devtools } from '@tanstack/devtools-vite'

import { tanstackStart } from '@tanstack/react-start/plugin/vite'

import viteReact, { reactCompilerPreset } from '@vitejs/plugin-react'
import babel from '@rolldown/plugin-babel'
import tailwindcss from '@tailwindcss/vite'
import { cloudflare } from '@cloudflare/vite-plugin'
import { viteStaticCopy } from 'vite-plugin-static-copy'

// PDF.js data files the book reader loads at runtime (see src/components/books/pdf-reader.tsx):
// CMaps and standard fonts for Arabic and other non-Latin text, plus WASM image decoders.
// Served from /pdfjs/ on our own origin instead of a third-party CDN.
const pdfjsDir = path
  .dirname(createRequire(import.meta.url).resolve('pdfjs-dist/package.json'))
  .replaceAll(path.sep, '/')

const config = defineConfig({
  staged: {
    '*': 'vp check --fix',
  },
  fmt: {
    // Generated by `wrangler types`.
    ignorePatterns: ['worker-configuration.d.ts'],
    singleQuote: true,
    semi: false,
  },
  lint: {
    ignorePatterns: ['worker-configuration.d.ts'],
    jsPlugins: [{ name: 'vite-plus', specifier: 'vite-plus/oxlint-plugin' }, '@shadcn/lint'],
    rules: {
      'vite-plus/prefer-vite-plus-imports': 'error',
      'shadcn/no-restyle': [
        'warn',
        {
          allow: ['layout'],
          deny: ['[--*', '[background-image*', '[mask*', '[-webkit-mask*'],
        },
      ],
      'shadcn/no-raw-colors': 'error',
      'shadcn/no-unknown-classes': 'error',
    },
    overrides: [
      {
        files: ['**/components/ui/**', '**/components/blocks/**'],
        rules: {
          'shadcn/no-restyle': 'off',
        },
      },
    ],
    options: { typeAware: true, typeCheck: true },
  },
  resolve: { tsconfigPaths: true },
  plugins: lazyPlugins(() => [
    devtools(),
    cloudflare({ viteEnvironment: { name: 'ssr' } }),
    tailwindcss(),
    viteStaticCopy({
      targets: ['cmaps', 'standard_fonts', 'wasm', 'iccs'].map((dir) => ({
        src: `${pdfjsDir}/${dir}/*`,
        dest: `pdfjs/${dir}`,
        rename: { stripBase: true },
      })),
    }),
    tanstackStart(),
    viteReact(),
    babel({ presets: [reactCompilerPreset()] }),
  ]),
})

export default config
